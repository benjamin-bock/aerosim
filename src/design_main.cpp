static std::string f0(double d) { std::ostringstream o; o << std::fixed << std::setprecision(0) << d; return o.str(); }
static std::string f1(double d) { std::ostringstream o; o << std::fixed << std::setprecision(1) << d; return o.str(); }

static std::string flapName(FlapType t) {
    switch (t) {
        case FlapType::None: return "none";
        case FlapType::Plain: return "plain";
        case FlapType::Split: return "split";
        case FlapType::SingleSlot: return "single-slot";
        case FlapType::Fowler: return "fowler";
        case FlapType::DoubleSlot: return "double-slot";
    }
    return "?";
}

static void writeReport(const DesignSpec& spec, const SynthesisResult& r,
                        const std::string& path) {
    std::ofstream out(path);
    auto f2 = [](double d) { std::ostringstream o; o << std::fixed << std::setprecision(2) << d; return o.str(); };
    auto f3 = [](double d) { std::ostringstream o; o << std::fixed << std::setprecision(3) << d; return o.str(); };

    out << "# Aircraft Conceptual Design Report\n\n";
    out << "Generated by AeroSim PlaneDesign (Raymer-based synthesis)\n\n";
    out << "## Requirements\n\n";
    out << "| Item | Value |\n|---|---|\n";
    out << "| Payload | " << f2(spec.payloadKg) << " kg |\n";
    out << "| Crew | " << f2(spec.crewKg) << " kg |\n";
    out << "| Range | " << f2(spec.rangeKm) << " km |\n";
    out << "| Cruise speed | " << f2(spec.cruiseSpeedMs) << " m/s at " << f2(spec.cruiseAltM) << " m |\n";
    out << "| Stall speed | " << f2(spec.stallSpeedMs) << " m/s |\n";
    out << "| Takeoff over " << f2(spec.obstacleM) << " m obstacle | " << f2(spec.takeoffDistM) << " m |\n";
    out << "| Rate of climb | " << f2(spec.rocMs) << " m/s at " << f2(spec.climbSpeedMs) << " m/s |\n";
    out << "| Max speed (SL) | " << f2(spec.maxSpeedMs) << " m/s |\n";
    out << "| Airfoil | NACA " << spec.airfoil << " |\n";
    out << "| Flaps | " << flapName(spec.flap) << " |\n";

    out << "\n## Weight Summary\n\n";
    out << "| Component | kg | % W0 |\n|---|---|---|\n";
    auto row = [&](const char* n, double kg) {
        out << "| " << n << " | " << f2(kg) << " | " << f2(100.0 * kg / std::max(r.w0Kg, 1.0)) << " |\n";
    };
    row("Wing", r.weights.wingKg);
    row("Fuselage", r.weights.fuselageKg);
    row("Horizontal tail", r.weights.htKg);
    row("Vertical tail", r.weights.vtKg);
    row("Engine (installed)", r.weights.engineKg);
    row("Landing gear", r.weights.gearKg);
    row("Fuel system", r.weights.fuelSystemKg);
    row("Flight controls", r.weights.flightControlsKg);
    row("Electrical", r.weights.electricalKg);
    row("Avionics", r.weights.avionicsKg);
    row("Furnishings", r.weights.FurnishingsKg);
    row("Paint/finish", r.weights.paintKg);
    row("**Empty weight**", r.weights.totalEmptyKg);
    row("**Fuel**", r.wfKg);
    row("Crew", spec.crewKg);
    row("Payload", spec.payloadKg);
    row("**MTOW (W0)**", r.w0Kg);
    out << "\nEmpty fraction (buildup): " << f3(r.weights.buildupFrac)
        << " | Raymer Table 3.1 regression: " << f3(r.weights.table31Frac) << "\n\n";

    out << "## Geometry\n\n";
    out << "| Item | Value |\n|---|---|\n";
    out << "| Wing area | " << f2(r.geo.wingArea) << " m² |\n";
    out << "| Span | " << f2(r.geo.span) << " m |\n";
    out << "| Aspect ratio | " << f2(r.geo.aspectRatio) << " |\n";
    out << "| Wing loading | " << f2(r.w0Kg * 9.81 / r.geo.wingArea) << " N/m² |\n";
    out << "| MAC | " << f3(r.geo.mac) << " m |\n";
    out << "| Fuselage length | " << f2(r.geo.fusLength) << " m |\n";
    out << "| Fuselage max diameter | " << f2(r.geo.fusMaxDiameter) << " m |\n";
    out << "| H-tail area (Vh=" << f2(spec.htVolumeCoeff) << ") | " << f2(r.geo.htArea) << " m² |\n";
    out << "| V-tail area (Vv=" << f2(spec.vtVolumeCoeff) << ") | " << f2(r.geo.vtArea) << " m² |\n";
    out << "| Total wetted area | " << f2(r.geo.swetTotal) << " m² |\n";

    out << "\n## Aerodynamics\n\n";
    out << "| Item | Value |\n|---|---|\n";
    out << "| CD0 | " << f3(r.aero.cd0) << " |\n";
    out << "| Oswald e | " << f3(r.aero.oswald) << " |\n";
    out << "| K | " << f3(r.aero.k) << " |\n";
    out << "| (L/D)max | " << f2(r.aero.ldMax) << " |\n";
    out << "| CLmax clean | " << f2(r.aero.clmaxClean) << " |\n";
    out << "| CLmax takeoff | " << f2(r.aero.clmaxTakeoff) << " |\n";
    out << "| CLmax landing | " << f2(r.aero.clmaxLanding) << " |\n";

    out << "\n## Propulsion\n\n";
    out << "| Item | Value |\n|---|---|\n";
    if (spec.propDriven) {
        out << "| Required power | " << f2(r.powerKW) << " kW (" << f2(r.powerKW * 1.341) << " hp) |\n";
        out << "| P/W | " << f2(r.pw) << " W/kg |\n";
        if (r.engineIdx >= 0) {
            const auto& e = engineDatabase()[r.engineIdx];
            out << "| Selected engine | " << e.model << " (" << f2(e.powerKW) << " kW, "
                << f2(e.massKg) << " kg, SFC " << f2(e.sfcKgPerkWh) << " kg/kWh) |\n";
        }
    } else {
        out << "| Required thrust | " << f2(r.tw * r.w0Kg * 9.81) << " N |\n";
        out << "| T/W | " << f3(r.tw) << " |\n";
    }
    out << "| Governing constraint | " << r.governingConstraint << " |\n";

    out << "\n## Predicted Performance\n\n";
    out << "| Item | Value |\n|---|---|\n";
    out << "| Range (with reserves) | " << f1(r.perf.rangeKm) << " km |\n";
    out << "| Service ceiling | " << f0(r.perf.ceilingM) << " m |\n";
    out << "| ROC at SL (best) | " << f2(r.perf.rocSLms) << " m/s at " << f2(r.perf.vBestClimb) << " m/s |\n";
    out << "| Max level speed (SL) | " << f2(r.perf.vMaxLevel) << " m/s |\n";
    out << "| Stall clean | " << f2(r.perf.vStallClean) << " m/s |\n";
    out << "| Stall landing config | " << f2(r.perf.vStallLanding) << " m/s |\n";
    out << "| Takeoff over obstacle | " << f1(r.perf.takeoffDistM) << " m |\n";
    out << "| Landing distance | " << f1(r.perf.landingDistM) << " m |\n";
    out << "| V-n: corner speed | " << f2(r.perf.vsPositive) << " m/s, dive " << f2(r.perf.vDive) << " m/s |\n";

    out << "\n## Convergence\n\n";
    out << "Converged: " << (r.converged ? "yes" : "NO") << " in " << r.iterations << " iterations\n\n";
    out << "| iter | W0 (kg) |\n|---|---|\n";
    for (size_t i = 0; i < r.w0History.size(); ++i)
        out << "| " << i + 1 << " | " << f2(r.w0History[i]) << " |\n";
    out.close();
}

static void writeConstraintCsv(const SynthesisResult& r, const DesignSpec& spec,
                              const std::string& path) {
    ConstraintAnalysis ca(r.aero, r.cset);
    auto lines = ca.compute(100.0, 2500.0, 50);
    std::ofstream out(path);
    out << "kind,label,ws,tw,pw\n";
    for (const auto& l : lines) {
        if (l.isUpperBoundOnWs) {
            out << "stall,stall," << l.wsLimit << ",,\n";
            continue;
        }
        for (size_t i = 0; i < l.ws.size(); ++i)
            out << (int)l.kind << "," << l.label << "," << l.ws[i] << ","
                << l.tw[i] << "," << l.pw[i] << "\n";
    }
    (void)spec;
    out.close();
}

static void writeWeightCsv(const SynthesisResult& r, const std::string& path) {
    std::ofstream out(path);
    out << "component,kg\n";
    out << "wing," << r.weights.wingKg << "\n";
    out << "fuselage," << r.weights.fuselageKg << "\n";
    out << "htail," << r.weights.htKg << "\n";
    out << "vtail," << r.weights.vtKg << "\n";
    out << "engine," << r.weights.engineKg << "\n";
    out << "gear," << r.weights.gearKg << "\n";
    out << "fuel_system," << r.weights.fuelSystemKg << "\n";
    out << "flight_controls," << r.weights.flightControlsKg << "\n";
    out << "electrical," << r.weights.electricalKg << "\n";
    out << "avionics," << r.weights.avionicsKg << "\n";
    out << "furnishings," << r.weights.FurnishingsKg << "\n";
    out << "paint," << r.weights.paintKg << "\n";
    out << "fuel," << r.wfKg << "\n";
    out << "crew," << "\n";
    out.close();
}

static void writeCarpetCsv(const TradeStudyResult& t, const std::string& path) {
    std::ofstream out(path);
    out << "ar,ws,w0_kg,power_kw,ld_max,converged\n";
    for (const auto& p : t.grid)
        out << p.ar << "," << p.ws << "," << p.w0 << "," << p.powerKW << ","
            << p.ldMax << "," << (p.converged ? 1 : 0) << "\n";
    out.close();
}

int main(int argc, char** argv) {
    DesignSpec spec;
    std::string reportPath = "output/design_report.md";
    std::string consPath = "output/constraints.csv";
    std::string weightPath = "output/weights.csv";
    std::string carpetPath = "output/carpet.csv";
    bool doCarpet = false;

    for (int i = 1; i < argc; ++i) {
        std::string a = argv[i];
        auto next = [&](double& d) { if (i + 1 < argc) d = std::atof(argv[++i]); };
        auto nextStr = [&](std::string& s) { if (i + 1 < argc) s = argv[++i]; };
        if (a == "-h" || a == "--help") {
            std::cout << "PlaneDesign v2: full Raymer synthesis\n";
            return 0;
        }
        else if (a == "-pay") next(spec.payloadKg);
        else if (a == "-crew") next(spec.crewKg);
        else if (a == "-range") next(spec.rangeKm);
        else if (a == "-vc") next(spec.cruiseSpeedMs);
        else if (a == "-alt") next(spec.cruiseAltM);
        else if (a == "-end") next(spec.enduranceH);
        else if (a == "-vs") next(spec.stallSpeedMs);
        else if (a == "-to") next(spec.takeoffDistM);
        else if (a == "-hobs") next(spec.obstacleM);
        else if (a == "-roc") next(spec.rocMs);
        else if (a == "-vcl") next(spec.climbSpeedMs);
        else if (a == "-vmax") next(spec.maxSpeedMs);
        else if (a == "-n") next(spec.nTurn);
        else if (a == "-ceil") next(spec.ceilingM);
        else if (a == "-ar") next(spec.aspectRatio);
        else if (a == "-af") nextStr(spec.airfoil);
        else if (a == "-jet") spec.propDriven = false;
        else if (a == "-eta") next(spec.propEff);
        else if (a == "-flap") {
            std::string f; nextStr(f);
            if (f == "plain") spec.flap = FlapType::Plain;
            else if (f == "split") spec.flap = FlapType::Split;
            else if (f == "single") spec.flap = FlapType::SingleSlot;
            else if (f == "fowler") spec.flap = FlapType::Fowler;
            else if (f == "double") spec.flap = FlapType::DoubleSlot;
            else spec.flap = FlapType::None;
        }
        else if (a == "-retract") spec.retractGear = true;
        else if (a == "-comp") spec.composite = true;
        else if (a == "-seats") { double d; next(d); spec.nSeats = (int)d; }
        else if (a == "-engines") { double d; next(d); spec.nEngines = (int)d; }
        else if (a == "-carpet") doCarpet = true;
        else if (a == "-report") nextStr(reportPath);
    }

    std::cout << "--- AeroSim PlaneDesign v2 (full synthesis) ---\n";
    SynthesisResult r = synthesizeDesign(spec);
    std::cout << std::fixed << std::setprecision(1);
    std::cout << (r.converged ? "[converged] " : "[NOT converged] ")
              << "after " << r.iterations << " iterations\n";
    if (!r.converged) {
        std::cout << "\n  *** The weight loop did not close. This usually means the\n"
                  << "  *** requirements are mutually very demanding for this size\n"
                  << "  *** (e.g. a low stall speed forcing a huge wing on a heavy\n"
                  << "  *** aircraft). The best iterate is reported below.\n"
                  << "  *** Tips: raise -vs, lengthen -to, or reduce -roc/-vmax.\n\n";
    }
    std::cout << "  W0 = " << r.w0Kg << " kg | We = " << r.weights.totalEmptyKg
              << " kg | Wf = " << r.wfKg << " kg\n";
    std::cout << "  S = " << r.wingArea << " m², b = " << r.span << " m (AR "
              << spec.aspectRatio << "), W/S = " << r.w0Kg * 9.81 / r.wingArea << " N/m²\n";
    std::cout << "  (L/D)max = " << r.aero.ldMax << ", CD0 = " << r.aero.cd0
              << ", CLmax_TO = " << r.aero.clmaxTakeoff << "\n";
    std::cout << "  Power = " << r.powerKW << " kW (" << r.powerKW * 1.341
              << " hp), governing: " << r.governingConstraint << "\n";
    if (r.engineIdx >= 0)
        std::cout << "  Engine: " << engineDatabase()[r.engineIdx].model << "\n";
    std::cout << "  Range = " << r.perf.rangeKm << " km, ceiling = " << r.perf.ceilingM
              << " m, ROC = " << r.perf.rocSLms << " m/s, TO dist = " << r.perf.takeoffDistM << " m\n";

    writeReport(spec, r, reportPath);
    writeConstraintCsv(r, spec, consPath);
    writeWeightCsv(r, weightPath);
    if (doCarpet) {
        std::vector<double> ars = {5, 6, 7, 8, 9, 10, 12};
        std::vector<double> wss = {400, 600, 800, 1000, 1200, 1400};
        TradeStudyResult t = carpetStudy(spec, ars, wss);
        writeCarpetCsv(t, carpetPath);
        if (t.found)
            std::cout << "  Carpet optimum: AR=" << t.optimum.ar << ", W/S=" << t.optimum.ws
                      << " -> W0=" << t.optimum.w0 << " kg\n";
    }
    std::cout << "Report: " << reportPath << "\n";
    return 0;
}
